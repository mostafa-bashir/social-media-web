// Generates src/styles/design-tokens.css from src/design-system/colors.tokens.json.
// Usage: pnpm tokens
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "src/design-system/colors.tokens.json");
const target = join(root, "src/styles/design-tokens.css");

const tokens = JSON.parse(readFileSync(source, "utf8"));
const HEX = /^#[0-9a-f]{6}$/i;

function block(selector, scheme) {
  const lines = Object.entries(tokens[scheme]).map(([name, value]) => {
    if (!HEX.test(value)) {
      throw new Error(`${scheme}.${name} must be a 6-digit hex color`);
    }
    return `  --ds-${name}: ${value};`;
  });
  return `${selector} {\n${lines.join("\n")}\n}`;
}

const lightKeys = Object.keys(tokens.light).sort().join();
const darkKeys = Object.keys(tokens.dark).sort().join();
if (lightKeys !== darkKeys) {
  throw new Error("light and dark token sets must define the same keys");
}

const css = `/* GENERATED by scripts/generate-design-tokens.mjs — do not edit by hand.
 * Source: src/design-system/colors.tokens.json (run \`pnpm tokens\`). */

${block(":root", "light")}

${block(':root[data-theme="dark"]', "dark")}
`;

writeFileSync(target, css);
console.log(`Wrote ${Object.keys(tokens.light).length} tokens to ${target}`);
